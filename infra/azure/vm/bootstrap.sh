#!/usr/bin/env bash
# Bring the stack up on the Azure VM. Idempotent: safe to re-run after every deploy.
# Run by infra/azure/deploy.sh as the admin user, from /opt/brain/app (the synced repo).
#   1. app .env from the Terraform-generated /opt/brain/env/azure.env
#   2. OpenMetadata JWT keys (DER) and Caddy's basic-auth hash
#   3. docker compose up (OpenMetadata + ES + Postgres + Fuseki, Atlas, agent-memory, Ollama, brain, Caddy)
#   4. replace OpenMetadata's default admin password, pull the Ollama models
#   5. restore the brain's Atlas data (first run), search indexes, OpenMetadata catalog, Foundry agents
set -euo pipefail
cd /opt/brain/app
log() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

set -a
# shellcheck disable=SC1091
source /opt/brain/env/azure.env
set +a

log "app settings (.env)"
umask 077
cat > .env <<EOF
# generated by infra/azure/vm/bootstrap.sh from /opt/brain/env/azure.env (do not edit here)
MONGODB_URI=mongodb://atlas:27017/?directConnection=true
MONGODB_DB=wisteria_brain
EMBEDDINGS_PROVIDER=ollama
OLLAMA_URL=http://ollama:11434
OLLAMA_EMBED_MODEL=nomic-embed-text
OPENMETADATA_URL=http://openmetadata-server:8585
OPENMETADATA_PUBLIC_URL=https://${SITE_HOST}:8443
OPENMETADATA_ADMIN_EMAIL=admin@open-metadata.org
OPENMETADATA_ADMIN_PASSWORD='${OPENMETADATA_ADMIN_PASSWORD}'
FUSEKI_URL=http://fuseki:3030
AGENT_MEMORY_URL=http://agent-memory:8000
AGENT_MEMORY_OPENAI_BASE_URL=http://ollama:11434/v1
FOUNDRY_PROJECT_ENDPOINT=${FOUNDRY_PROJECT_ENDPOINT}
FOUNDRY_SUBSCRIPTION_ID=${FOUNDRY_SUBSCRIPTION_ID}
FOUNDRY_RESOURCE_GROUP=${FOUNDRY_RESOURCE_GROUP}
FOUNDRY_ACCOUNT=${FOUNDRY_ACCOUNT}
FOUNDRY_PROJECT=${FOUNDRY_PROJECT}
FOUNDRY_AGENT_MODEL=${FOUNDRY_AGENT_MODEL}
FOUNDRY_GATEWAY_URL=${FOUNDRY_GATEWAY_URL}
FOUNDRY_USE_MANAGED_IDENTITY=1
FOUNDRY_AGENT_KEYS='${FOUNDRY_AGENT_KEYS}'
JWT_KEY_ID=${JWT_KEY_ID}
FERNET_KEY=${FERNET_KEY}
EOF
umask 022

log "OpenMetadata signing keys"
K=/opt/brain/secrets/jwt
if [ ! -f "$K/private_key.der" ]; then
  openssl pkcs8 -topk8 -inform PEM -outform DER -nocrypt -in "$K/private.pem" -out "$K/private_key.der"
  openssl rsa -in "$K/private.pem" -pubout -outform DER -out "$K/public_key.der" 2>/dev/null
fi
chmod 755 "$K"
chmod 644 "$K/private_key.der" "$K/public_key.der" # read by the OpenMetadata container user

log "Caddy basic auth"
HASH=$(docker run --rm caddy:2 caddy hash-password --plaintext "$WEB_PASSWORD")
printf 'SITE_HOST=%s\nWEB_USER=%s\nWEB_PASSWORD_HASH=%s\n' "$SITE_HOST" "$WEB_USER" "$HASH" > /opt/brain/env/caddy.env
chmod 600 /opt/brain/env/caddy.env

C="docker compose -f docker-compose.azure.yml"
log "docker compose up"
$C up -d --build --remove-orphans

log "waiting for OpenMetadata"
for _ in $(seq 1 120); do curl -sf localhost:8585/api/v1/system/version >/dev/null && break; sleep 5; done
curl -sf localhost:8585/api/v1/system/version && echo

log "OpenMetadata admin password"
DEFAULT=$(curl -s -X POST localhost:8585/api/v1/users/login -H 'Content-Type: application/json' \
  -d "{\"email\":\"admin@open-metadata.org\",\"password\":\"$(printf admin | base64)\"}" | jq -r '.accessToken // empty')
if [ -n "$DEFAULT" ]; then
  jq -n --arg p "$OPENMETADATA_ADMIN_PASSWORD" '{username:"admin",oldPassword:"admin",newPassword:$p,confirmPassword:$p,requestType:"SELF"}' |
    curl -sf -X PUT localhost:8585/api/v1/users/changePassword -H "Authorization: Bearer $DEFAULT" -H 'Content-Type: application/json' -d @- >/dev/null
  echo "default admin password replaced"
else
  echo "already replaced"
fi

log "Ollama models"
docker exec brain_ollama ollama pull nomic-embed-text >/dev/null
docker exec brain_ollama ollama pull qwen2.5:3b >/dev/null
echo "nomic-embed-text, qwen2.5:3b ready"

log "brain data in Atlas"
DOCS=$(docker exec brain_atlas mongosh --quiet wisteria_brain --eval 'db.docs.estimatedDocumentCount()' 2>/dev/null || echo 0)
ARCHIVE=/opt/brain/data/wisteria_brain.archive.gz
if [ "${DOCS:-0}" -eq 0 ] && [ -f "$ARCHIVE" ]; then
  docker exec -i brain_atlas mongorestore --archive --gzip --drop --nsInclude 'wisteria_brain.*' < "$ARCHIVE"
fi
docker exec brain_atlas mongosh --quiet wisteria_brain --eval 'printjson({docs: db.docs.estimatedDocumentCount(), chunks: db.chunks.estimatedDocumentCount(), entities: db.entities.estimatedDocumentCount()})'

log "waiting for the brain container (npm ci + build)"
for _ in $(seq 1 180); do docker exec brain_app curl -sf localhost:8787/api/team >/dev/null 2>&1 && break; sleep 5; done
B="docker exec -w /app brain_app npx tsx"

log "search indexes"
$B packages/brain/scripts/indexes.ts

log "agent-memory"
for _ in $(seq 1 60); do docker exec brain_app curl -sf http://agent-memory:8000/health >/dev/null 2>&1 && break; sleep 5; done
docker exec brain_app curl -s http://agent-memory:8000/health | jq -c '{status, workers: .workers.running}'

log "OpenMetadata catalog (ontology, sources, collections, lineage, agents)"
$B packages/brain/scripts/om-setup.ts --no-native
docker restart openmetadata_fuseki >/dev/null # refresh the RDFS/OWL reasoners over the new graph
docker restart brain_app >/dev/null           # pick up the agents' OpenMetadata bots in the gateway

log "Foundry agents"
for _ in $(seq 1 120); do docker exec brain_app curl -sf localhost:8787/api/team >/dev/null 2>&1 && break; sleep 5; done
$B packages/brain/scripts/foundry-agents.ts --agents-only

log "checks"
printf 'gateway without a key: '; curl -s -o /dev/null -w '%{http_code}\n' -X POST "https://${SITE_HOST}/agents/support_lead/mcp"
printf 'web app without login: '; curl -s -o /dev/null -w '%{http_code}\n' "https://${SITE_HOST}/team"
printf 'OpenMetadata UI:       '; curl -s -o /dev/null -w '%{http_code}\n' "https://${SITE_HOST}:8443/"
echo
echo "App:          https://${SITE_HOST}/team   (user ${WEB_USER})"
echo "OpenMetadata: https://${SITE_HOST}:8443   (admin@open-metadata.org)"
